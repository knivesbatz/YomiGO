#!/usr/bin/env node
// Makes the release signing key once, outside the repo, and writes the public half into the source.
// usage: node tools/release_keys.mjs        create key if missing, write src/updater/pubkey.h
//        node tools/release_keys.mjs sign <files...>   writes <file>.sig for each
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const dir = path.join(os.homedir(), ".yomigo");
const keyPath = path.join(dir, "release_key.pem");
const root = path.dirname(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1")));

if (process.argv[2] === "sign") {
  const key = fs.readFileSync(keyPath);
  for (const f of process.argv.slice(3)) {
    fs.writeFileSync(f + ".sig", crypto.sign("RSA-SHA256", fs.readFileSync(f), key));
    console.log("signed", f);
  }
  process.exit(0);
}
if (!fs.existsSync(keyPath)) {
  fs.mkdirSync(dir, { recursive: true });
  const { privateKey } = crypto.generateKeyPairSync("rsa", { modulusLength: 3072 });
  fs.writeFileSync(keyPath, privateKey.export({ type: "pkcs8", format: "pem" }), { mode: 0o600 });
  console.log("new key at", keyPath, "- back this up. Without it, future updates can't be signed.");
}
const pub = crypto.createPublicKey(fs.readFileSync(keyPath)).export({ format: "jwk" });
const n = Buffer.from(pub.n, "base64url"), e = Buffer.from(pub.e, "base64url");
// Windows PUBLICKEYBLOB: header, RSAPUBKEY, then the modulus little-endian
const head = Buffer.alloc(20);
head.writeUInt8(6, 0); head.writeUInt8(2, 1); head.writeUInt16LE(0, 2); head.writeUInt32LE(0x2400, 4); // PUBLICKEYBLOB, CALG_RSA_SIGN
head.write("RSA1", 8, "latin1"); head.writeUInt32LE(n.length * 8, 12);
head.writeUInt32LE(parseInt(e.toString("hex"), 16), 16);
const blob = Buffer.concat([head, Buffer.from(n).reverse()]);
const lines = [];
for (let i = 0; i < blob.length; i += 16) lines.push([...blob.subarray(i, i + 16)].join(","));
fs.writeFileSync(path.join(root, "src", "updater", "pubkey.h"),
  `/* Public half of the release key, generated by tools/release_keys.mjs. */\nstatic const unsigned char YG_PUBKEY[] = {\n${lines.join(",\n")}\n};\n`);
console.log("wrote pubkey.h");
